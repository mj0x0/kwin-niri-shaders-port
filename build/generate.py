# ----------------------------------------------------------------------- helpers


def extract_function(src, fname):
    """Return the full text of a top-level function `fname` via brace matching."""
    m = re.search(r'(?m)^\s*(?:float|vec[234]|int|void|mat[234])\s+' +
                  re.escape(fname) + r'\s*\(', src)
    if not m:
        raise RuntimeError("function %s not found" % fname)
    start = m.start()
    i = src.index('{', m.start())
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{':
            depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0:
                return src[start:j + 1]
    raise RuntimeError("unbalanced braces in %s" % fname)


def parse_config(path):
    """Return (duration_ms, curve) from a Niri effect config file."""
    duration, curve = 500, "ease-out-cubic"
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line.startswith("duration-ms"):
                duration = int(line.split()[1])
            elif line.startswith("curve"):
                curve = line.split('"')[1] if '"' in line else curve
    return duration, curve


def camel(nick):
    return "Niri" + re.sub(r'(^|-)(\w)', lambda m: m.group(2).upper(), nick) + "Effect"


def pretty(nick):
    return re.sub(r'(^|-)(\w)', lambda m: (" " if m.group(1) else "") + m.group(2).upper(), nick)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


# ------------------------------------------------------------------------- build


def build_effect(nick, role="open_close"):
    r = ROLES[role]
    d = os.path.join(SRC, nick)
    open_src = open(os.path.join(d, "open.glsl")).read()
    close_src = open(os.path.join(d, "close.glsl")).read()
    duration, curve = parse_config(os.path.join(d, "config"))

    if curve != "ease-out-cubic":
        print("  WARNING: %s uses curve %r (shim assumes ease-out-cubic)" % (nick, curve))

    uses_seed = "niri_random_seed" in open_src or "niri_random_seed" in close_src

    # open.glsl in full (helpers + open_color) + only close_color from close.glsl.
    body = open_src.rstrip() + "\n\n" + extract_function(close_src, "close_color") + "\n"

    seed_decl = "uniform float uSeed;      // per-animation random phase, [0, 1)\n" if uses_seed else ""
    core = COMPAT_CORE.replace("%SEED_DECL%", seed_decl) + body + MAIN_CORE
    legacy = COMPAT_LEGACY.replace("%SEED_DECL%", seed_decl) + body + MAIN_LEGACY

    pkg = "kwin6_effect_" + nick.replace("-", "_") + r["suffix"]
    name = pretty(nick) + r["name_suffix"]
    cls = camel(nick) + ("Minimize" if role == "minimize" else "")
    seed_line = ('        effect.setUniform(this.shader, "uSeed", Math.random());'
                 if uses_seed else "")
    main_js_tpl = MAIN_JS_MINIMIZE if role == "minimize" else MAIN_JS

    base = os.path.join(OUT, pkg)
    write(os.path.join(base, "metadata.json"),
          METADATA.format(name=name, desc=r["desc"] % nick, nick=nick, pkg=pkg,
                          category=r["category"], exclusive=r["exclusive"]))
    write(os.path.join(base, "contents/code/main.js"),
          main_js_tpl.format(name=name, nick=nick, cls=cls, duration=duration,
                             seed_line=seed_line))
    write(os.path.join(base, "contents/shaders/%s_core.frag" % nick), core)
    write(os.path.join(base, "contents/shaders/%s.frag" % nick), legacy)
    write(os.path.join(base, "contents/config/main.xml"), MAIN_XML.format(duration=duration))
    write(os.path.join(base, "contents/ui/config.ui"), CONFIG_UI)

    # sanity: metadata.json must parse
    json.loads(open(os.path.join(base, "metadata.json")).read())
    return pkg, duration, uses_seed


def discoverable(nick):
    d = os.path.join(SRC, nick)
    return (os.path.isdir(d) and nick not in SKIP
            and os.path.exists(os.path.join(d, "open.glsl"))
            and os.path.exists(os.path.join(d, "close.glsl"))
            and os.path.exists(os.path.join(d, "config")))


def main():
    role = "open_close"
    if len(sys.argv) > 1 and sys.argv[1] in ("--role",) and len(sys.argv) > 2:
        role = sys.argv[2]
    elif len(sys.argv) > 1 and sys.argv[1] in ROLES:
        role = sys.argv[1]

    if role == "minimize":
        nicks = [n for n in MINIMIZE_SET if discoverable(n)]
    else:
        nicks = [n for n in sorted(os.listdir(SRC)) if discoverable(n)]

    built = []
    for nick in nicks:
        pkg, dur, seed = build_effect(nick, role)
        built.append((nick, pkg, dur, seed))
        print("  built %-28s duration=%-5s seed=%s" % (pkg, dur, seed))

    print("\nGenerated %d '%s' effect packages into %s" % (len(built), role, OUT))
    return built


if __name__ == "__main__":
    main()
