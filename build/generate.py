MAIN_JS = """// SPDX-License-Identifier: MIT
//
// KWin 6 scripted window open/close effect: "{name}".
// Auto-generated port of the Niri custom-shader "{nick}".

"use strict";

const blacklist = [
    "ksmserver ksmserver",
    "ksmserver-logout-greeter ksmserver-logout-greeter",
    "ksplashqml ksplashqml",
];

class {cls} {{
    constructor() {{
        effect.configChanged.connect(this.loadConfig.bind(this));
        effect.animationEnded.connect(this.cleanupForcedRoles.bind(this));
        effects.windowAdded.connect(this.slotWindowAdded.bind(this));
        effects.windowClosed.connect(this.slotWindowClosed.bind(this));
        effects.windowDataChanged.connect(this.slotWindowDataChanged.bind(this));

        this.shader = effect.addFragmentShader(Effect.MapTexture, "{nick}.frag");

        this.loadConfig();
    }}

    loadConfig() {{
        this.duration = animationTime(effect.readConfig("Duration", {duration}));
    }}

    static shouldAnimateWindow(window) {{
        if (window.windowClass == "plasmashell plasmashell"
                || window.windowClass == "plasmashell org.kde.plasmashell") {{
            return window.hasDecoration;
        }}
        if (!window.hasDecoration && window.onAllDesktops) {{
            return false;
        }}
        if (blacklist.indexOf(window.windowClass) != -1) {{
            return false;
        }}
        if (window.hasDecoration) {{
            return true;
        }}
        if (window.popupWindow) {{
            return false;
        }}
        if (window.lockScreen || window.outline) {{
            return false;
        }}
        if (!window.managed) {{
            return false;
        }}
        return window.normalWindow || window.dialog;
    }}

    setupForcedRoles(window) {{
        window.setData(Effect.WindowForceBackgroundContrastRole, true);
        window.setData(Effect.WindowForceBlurRole, true);
    }}

    cleanupForcedRoles(window) {{
        window.setData(Effect.WindowForceBackgroundContrastRole, null);
        window.setData(Effect.WindowForceBlurRole, null);
    }}

    startAnimation(window, forOpening) {{
        this.setupForcedRoles(window);

        effect.setUniform(this.shader, "uForOpening", forOpening ? 1.0 : 0.0);
{seed_line}
        return animate({{
            window: window,
            curve: QEasingCurve.Linear,
            duration: this.duration,
            animations: [
                {{
                    type: Effect.ShaderUniform,
                    fragmentShader: this.shader,
                    uniform: "uProgress",
                    from: 0.0,
                    to: 1.0,
                }},
            ],
        }});
    }}

    slotWindowAdded(window) {{
        if (effects.hasActiveFullScreenEffect) return;
        if (!{cls}.shouldAnimateWindow(window)) return;
        if (!window.visible) return;
        if (effect.isGrabbed(window, Effect.WindowAddedGrabRole)) return;
        window.niriInAnimation = this.startAnimation(window, true);
    }}

    slotWindowClosed(window) {{
        if (effects.hasActiveFullScreenEffect) return;
        if (!{cls}.shouldAnimateWindow(window)) return;
        if (!window.visible || window.skipsCloseAnimation) return;
        if (effect.isGrabbed(window, Effect.WindowClosedGrabRole)) return;
        if (window.niriInAnimation) {{
            cancel(window.niriInAnimation);
            delete window.niriInAnimation;
        }}
        window.niriOutAnimation = this.startAnimation(window, false);
    }}

    slotWindowDataChanged(window, role) {{
        if (role == Effect.WindowAddedGrabRole) {{
            if (window.niriInAnimation && effect.isGrabbed(window, role)) {{
                cancel(window.niriInAnimation);
                delete window.niriInAnimation;
                this.cleanupForcedRoles(window);
            }}
        }} else if (role == Effect.WindowClosedGrabRole) {{
            if (window.niriOutAnimation && effect.isGrabbed(window, role)) {{
                cancel(window.niriOutAnimation);
                delete window.niriOutAnimation;
                this.cleanupForcedRoles(window);
            }}
        }}
    }}
}}

new {cls}();
"""

# Minimize / unminimize variant. KWin 6 removed the effects.windowMinimized /
# windowUnminimized signals that older tutorials used; the current path is the
# per-window EffectWindow.minimizedChanged signal + the window.minimized bool.
# We attach a listener to every window (existing ones at startup, new ones via
# windowAdded) and drive the shader: minimized -> "leaving" (close body),
# unminimized -> "returning" (open body).
MAIN_JS_MINIMIZE = """// SPDX-License-Identifier: MIT
//
// KWin 6 scripted MINIMIZE/unminimize effect: "{name}".
// Auto-generated port of the Niri custom-shader "{nick}" (minimize role).

"use strict";

const blacklist = [
    "ksmserver ksmserver",
    "ksmserver-logout-greeter ksmserver-logout-greeter",
    "ksplashqml ksplashqml",
];

class {cls} {{
    constructor() {{
        effect.configChanged.connect(this.loadConfig.bind(this));
        this.shader = effect.addFragmentShader(Effect.MapTexture, "{nick}.frag");
        this.loadConfig();

        effects.windowAdded.connect(this.watch.bind(this));

        // Attach to windows that already exist when the effect loads.
        const existing = effects.stackingOrder;
        for (let i = 0; i < existing.length; i++) {{
            this.watch(existing[i]);
        }}
    }}

    loadConfig() {{
        this.duration = animationTime(effect.readConfig("Duration", {duration}));
    }}

    static shouldAnimateWindow(window) {{
        if (blacklist.indexOf(window.windowClass) != -1) {{
            return false;
        }}
        if (window.popupWindow || window.lockScreen || window.outline) {{
            return false;
        }}
        if (!window.managed) {{
            return false;
        }}
        return window.normalWindow || window.dialog;
    }}

    watch(window) {{
        if (window.niriMinWatched) {{
            return;
        }}
        window.niriMinWatched = true;
        // Per-window signal: KWin 6 has no effects.windowMinimized.
        window.minimizedChanged.connect(this.onMinimizedChanged.bind(this, window));
    }}

    setupForcedRoles(window) {{
        window.setData(Effect.WindowForceBackgroundContrastRole, true);
        window.setData(Effect.WindowForceBlurRole, true);
    }}

    onMinimizedChanged(window) {{
        if (effects.hasActiveFullScreenEffect) {{
            return;
        }}
        if (!{cls}.shouldAnimateWindow(window)) {{
            return;
        }}

        if (window.niriMinAnim) {{
            cancel(window.niriMinAnim);
            delete window.niriMinAnim;
        }}

        // minimized  -> window leaving   -> "close" body (uForOpening = 0)
        // unminimized-> window returning -> "open"  body (uForOpening = 1)
        const returning = !window.minimized;
        this.setupForcedRoles(window);
        effect.setUniform(this.shader, "uForOpening", returning ? 1.0 : 0.0);
{seed_line}
        window.niriMinAnim = animate({{
            window: window,
            curve: QEasingCurve.Linear,
            duration: this.duration,
            animations: [
                {{
                    type: Effect.ShaderUniform,
                    fragmentShader: this.shader,
                    uniform: "uProgress",
                    from: 0.0,
                    to: 1.0,
                }},
            ],
        }});
    }}
}}

new {cls}();
"""

